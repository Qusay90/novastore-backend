const searchable = value => String(value || '').toLocaleLowerCase('tr-TR').normalize('NFKD').replace(/[\u0300-\u036f]/g, '').replace(/ı/g, 'i');
/** Match all search words; Turkish input also matches its plain Latin spelling. */
export function filterCampaignMedia(query = '', category = 'all') {
  const words = searchable(query).trim().split(/\s+/).filter(Boolean);
  return CAMPAIGN_MEDIA.filter(item => (category === 'all' || item.category === category) &&
    words.every(word => searchable([item.label, item.categoryLabel, item.alt, item.keywords].join(' ')).includes(word)));
}

